// Run with Node 24: node --experimental-strip-types scripts/test-operations.mjs
import assert from 'node:assert/strict';
import {summarise,supplierCsv,csvCell} from '../app/lib/operations-summary.ts';
import {readAll} from '../app/lib/paginated-read.ts';
const inv=(id,pharmacy_id='p1')=>({id,pharmacy_id,supplier:'=formula',invoice_number:id,invoice_date:'2026-10-01',gross_total:12,created_at:'2026-10-01'});
const line=(id,qty,flags=[])=>({id,invoice_id:id,qty_ordered:2,qty_received:qty,flags,credit_request_id:null});
const summary=summarise([inv('a'),inv('b'),inv('c'),inv('d','p2'),inv('empty')],[line('a',null),line('b',2),line('c',1),line('d',2,['damaged']),line('deleted',null)],[{id:'c',pharmacy_id:'p1',supplier:'=formula',status:'sent',total_amount:4,sent_at:'2026-09-01'},{id:'r',pharmacy_id:'p1',supplier:'x',status:'resolved',total_amount:999,sent_at:null}],Date.parse('2026-10-13'));
assert.equal(summary.receipts[0].complete,false);
assert.equal(summary.receipts[0].pending,1);
assert.equal(summary.receipts[1].complete,true);
assert.equal(summary.receipts[2].exceptions,1);
assert.equal(summary.receipts[3].exceptions,1);
assert.equal(summary.receipts[4].complete,false);
assert.equal(summary.suppliers.length,2);
assert.equal(summary.suppliers.reduce((n,r)=>n+r.pending,0),1);
assert.equal(summary.openClaims.length,1);
assert.equal(summary.agedClaims.length,1);
const draftSummary=summarise([],[],[{id:'draft',pharmacy_id:'p1',supplier:'aver',status:'draft',total_amount:5,sent_at:'2020-01-01'}],Date.parse('2026-10-13'));
assert.equal(draftSummary.openClaims.length,1);
assert.equal(draftSummary.agedClaims.length,0);
assert.match(supplierCsv(summary.suppliers),/"'=formula"/);
assert.equal(csvCell('  =2+2'),'"\'  =2+2"');
assert.equal(csvCell('a,"b"'),'"a,""b"""');
const calls=[];
const rows=await readAll(async after=>{calls.push(after);return {data:after===null?[{id:'a'},{id:'b'}]:after==='b'?[{id:'c'}]:[],error:null}});
assert.equal(rows.length,3);
assert.deepEqual(calls,[null,'b','c']);
await assert.rejects(readAll(async()=>({data:null,error:{message:'blocked'}})),/blocked/);
await assert.rejects(readAll(async()=>({data:[{id:'a'}],error:null})),/did not advance/);
console.log('Operations summary tests passed.');
